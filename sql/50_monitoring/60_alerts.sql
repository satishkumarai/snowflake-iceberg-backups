CREATE OR REPLACE ALERT ${ADMIN_DB}.MONITORING.ALERT_STALE_BACKUPS
  WAREHOUSE = ${WAREHOUSE}
  SCHEDULE = '60 MINUTE'
  IF (EXISTS (
    SELECT 1 FROM ${ADMIN_DB}.MONITORING.V_BACKUP_FRESHNESS
    WHERE minutes_since_last_backup > 2 * TRY_TO_NUMBER(REGEXP_SUBSTR(schedule, '\\d+')) + 180))
  THEN CALL SYSTEM$SEND_SNOWFLAKE_NOTIFICATION(
         SNOWFLAKE.NOTIFICATION.TEXT_PLAIN('Stale Snowflake backup sets detected: see V_BACKUP_FRESHNESS'),
         SNOWFLAKE.NOTIFICATION.EMAIL_INTEGRATION_CONFIG('${EMAIL_INTEGRATION}', 'Backup freshness', ARRAY_CONSTRUCT('${ALERT_EMAIL}')));
-- +180 min absorbs ACCOUNT_USAGE latency. Resume after review: ALTER ALERT ... RESUME;
